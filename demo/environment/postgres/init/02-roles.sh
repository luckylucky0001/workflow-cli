# shellcheck shell=bash
# workctl demo: PostgreSQL roles. Sourced by docker-entrypoint-initdb.d (runs as the `postgres`
# OS user) and re-runnable as root via ../provision-users.sh (idempotent).
#
#   workctl_ro  read-only diagnostics role used by workctl (profile demo):
#               LOGIN, pg_read_all_stats (all of pg_stat_activity / pg_stat_statements text),
#               CONNECT on demo_orders, SELECT on customers/orders/order_items (NOT internal_ledger),
#               default_transaction_read_only=on, statement_timeout=30s, CONNECTION LIMIT 20.
#
# The password comes from /run/secrets/pg_ro_password (generated by up.sh). When the entrypoint
# cannot read it (secret files are mode 600 root and init runs as `postgres`), the role is created
# NOLOGIN; provision-users.sh then sets the password and LOGIN as root inside the container.
# The password is read by psql itself (\set with backticks) — never on a command line, never printed.

_wk_psql() {
  if declare -F docker_process_sql >/dev/null 2>&1; then
    docker_process_sql --dbname demo_orders
  else
    psql -v ON_ERROR_STOP=1 --no-psqlrc -q --username postgres --dbname demo_orders
  fi
}

if [ -r /run/secrets/pg_ro_password ] && [ -s /run/secrets/pg_ro_password ]; then
  _wk_login="\\set ro_pw \`tr -d '\\r\\n' < /run/secrets/pg_ro_password\`
ALTER ROLE workctl_ro LOGIN PASSWORD :'ro_pw';"
else
  _wk_login="ALTER ROLE workctl_ro NOLOGIN;"
  echo "[workctl-demo] pg_ro_password not readable by $(id -un); workctl_ro created NOLOGIN (run demo/environment/postgres/provision-users.sh)"
fi

_wk_psql <<EOSQL
DO \$\$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'workctl_ro') THEN
    CREATE ROLE workctl_ro NOLOGIN;
  END IF;
END \$\$;
ALTER ROLE workctl_ro CONNECTION LIMIT 20;
ALTER ROLE workctl_ro SET default_transaction_read_only = on;
ALTER ROLE workctl_ro SET statement_timeout = '30s';
GRANT pg_read_all_stats TO workctl_ro;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
GRANT CONNECT ON DATABASE demo_orders TO workctl_ro;
GRANT USAGE ON SCHEMA public TO workctl_ro;
GRANT SELECT ON customers, orders, order_items TO workctl_ro;
REVOKE ALL ON internal_ledger FROM workctl_ro;
${_wk_login}
EOSQL

unset _wk_login
unset -f _wk_psql
